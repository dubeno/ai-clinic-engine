class MedicalPDF(FPDF):
    def header(self):
        self.set_font("simhei", "", 10)
        self.set_text_color(128, 128, 128)
        self.cell(0, 8, "孕前和孕期保健指南 完整参考", align="C", new_x="LMARGIN", new_y="NEXT")
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(3)

    def footer(self):
        self.set_y(-15)
        self.set_font("simhei", "", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"第 {self.page_no()} 页", align="C")

    def ch_title(self, t):
        self.set_font("simhei", "", 14)
        self.set_text_color(0, 51, 102)
        self.cell(0, 10, t, new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(0, 102, 204)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def sec_title(self, t):
        self.set_font("simhei", "", 12)
        self.set_text_color(51, 51, 51)
        self.cell(0, 8, t, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def txt(self, t):
        self.set_font("simhei", "", 10)
        self.set_text_color(0, 0, 0)
        self.multi_cell(0, 6, t)
        self.ln(2)

    def bul(self, t):
        self.set_font("simhei", "", 10)
        self.set_text_color(0, 0, 0)
        x = self.get_x()
        self.cell(8, 6, "-")
        self.multi_cell(0, 6, t)
        self.ln(1)


